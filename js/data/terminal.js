export function notepadText(gm) {
  const l = [
    "// ЛИЧНЫЙ БЛОКНОТ / МОРОЗОВ А.В. //",
    "",
    `Виток: ${gm.loopCount}`,
    `Найдено записок: ${gm.notesRead.size}/4`,
    `Ключ №3: ${gm.inventory.includes("Ржавый лабораторный ключ №3") ? "ЕСТЬ" : "НЕТ"}`,
    `Ключ от щита: ${gm.inventory.includes("Ключ от щитовой") ? "ЕСТЬ" : "НЕТ"}`,
    `Свет на этаже: ${gm.flags.fuse_fixed ? "ЕСТЬ" : "НЕТ"}`,
    `Ссылка node_1988: ${gm.flags.node_visited ? "ПРОСМОТРЕНА" : "—"}`,
    "",
  ];

  if (gm.loopCount === 0) {
    l.push(
      "Вечер пятницы. Серверная. Щелчок реле — и белая вспышка.",
      "Я не помню, как попал домой.",
      "Дверь не открывается наружу — там только бетон и туман.",
      "Надо осмотреть квартиры соседей.",
    );
  } else if (gm.loopCount === 1) {
    l.push(
      "Второй виток. Кв. 44 открылась.",
      "Я больше не уверен, что я — это я.",
      "На стене кв. 43 — схемы моего мозга, сшитые с перфолентой.",
    );
  } else if (gm.loopCount === 2) {
    l.push(
      "Третий виток. Голоса в квартирах сместились.",
      "Монолог из «Маяка-205» теперь отстаёт на две секунды.",
      "Кажется, я становлюсь эхом самого себя.",
    );
  } else if (gm.loopCount >= 3) {
    l.push(
      "Витков больше, чем я могу сосчитать.",
      "Стек переполнен.",
      "Осталась одна точка синхронизации в сети.",
      "Пора принять решение.",
    );
  }

  return l.join("\n");
}

// Архив собранных записок — каждая найденная бумага, что игрок подобрал
// и уже читал как «письмо», остаётся здесь для повторного просмотра.
export function notesArchiveText(gm) {
  if (!gm.noteLog || gm.noteLog.length === 0) {
    return [
      "// ЗАПИСКИ //",
      "",
      "Пока не найдено ни одной записки.",
      "Ищи их в собственной квартире и у соседей —",
      "открытая записка сама сохранится здесь.",
    ].join("\n");
  }

  const lines = ["// ЗАПИСКИ //", `Собрано: ${gm.noteLog.length}`, ""];
  gm.noteLog.forEach((n, i) => {
    lines.push(`--- ${i + 1}. ${n.title} ---`);
    lines.push(n.text);
    lines.push("");
  });
  return lines.join("\n");
}

