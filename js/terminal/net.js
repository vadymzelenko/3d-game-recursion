export function normalizeUrl(u) {
  return String(u || "").trim()
    .replace(/^https?:\/\//i, "")
    .replace(/\/+$/, "")
    .toLowerCase();
}

export function isExternal(url) {
  return /^gost-1988\.su/.test(normalizeUrl(url));
}

export function page(url, state) {
  const key = normalizeUrl(url) || HOME;
  const fn = PAGES[key];
  return fn ? fn(state) : null;
}

// Настоящий адрес ARG-архива, который откроется во «внешнем мире» —
// в новой вкладке браузера, за пределами игры.
export function externalHref(url) {
  const path = normalizeUrl(url).replace(/^gost-1988\.su\/?/, "");
  const route = path.replace(/\.pdf$/, "") || "";
  return new URL("arg/index.html#/" + route, location.href).href;
}
